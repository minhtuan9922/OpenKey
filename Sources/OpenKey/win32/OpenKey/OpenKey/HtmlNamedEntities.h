constexpr bool validTable() {
    for (size_t index = 0; index < entries.size(); ++index) {
        const auto& entry = entries[index];
        if (entry.name.empty() || (index && entries[index - 1].name >= entry.name))
            return false;
        for (const auto scalar : { entry.first, entry.second }) {
            if (scalar > 0x10FFFFu || (scalar >= 0xD800u && scalar <= 0xDFFFu))
                return false;
        }
        if (!entry.first) return false;
    }
    return true;
}
static_assert(validTable(), "Named entities must be sorted, unique Unicode scalars.");

inline const Entry* find(std::string_view name) {
    const auto match = std::lower_bound(entries.begin(), entries.end(), name,
        [](const Entry& entry, std::string_view key) { return entry.name < key; });
    return match != entries.end() && match->name == name ? &*match : nullptr;
}
