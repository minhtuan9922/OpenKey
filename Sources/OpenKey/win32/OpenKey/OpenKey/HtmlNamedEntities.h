constexpr bool validLegacyNames() {
    for (size_t index = 0; index < legacyNames.size(); ++index) {
        if (index && legacyNames[index - 1] >= legacyNames[index]) return false;
        bool found = false;
        for (const auto& entry : entries) if (entry.name == legacyNames[index]) {
            found = true;
            break;
        }
        if (!found) return false;
    }
    return true;
}
